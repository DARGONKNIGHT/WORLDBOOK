/* Game 5 / v34 economic sandbox. All balances and quotes are explicit S fixtures.
 * No real money, banking, employment contract or user-authorized third-party action.
 * NPCs decide negotiations; only explicit out-of-character fixtures can settle books.
 */
(function(root,factory){
  const api=factory(typeof module==="object"&&module.exports?require("./engine.js"):root.EarthGame,
    typeof module==="object"&&module.exports?require("./society.js"):root.EarthSociety);
  if(typeof module==="object"&&module.exports)module.exports=api;
  else root.EarthEconomy=api;
})(typeof globalThis!=="undefined"?globalThis:this,function(E,S){
  "use strict";
  const MINUTE=60000, PARTIES=["P014","P015"], PAYER="P014", PROVIDER="P015";
  const validAmount=n=>Number.isSafeInteger(n)&&n>=0&&n<=1000000000;
  const check=(ok,msg)=>{if(!ok)throw Error(msg);};
  function ensure(s){
    check(s&&s.player&&Number.isFinite(s.time),"无效游戏状态");
    if(!s.economy)s.economy={version:1,accounts:{},openingAccounts:{},fixtures:{},quotes:[],ledger:[],transfers:[],seq:0,history:[]};
    check(s.economy.version===1,"不支持的经济数据版本");
    return s.economy;
  }
  function caseOf(s,id){
    return S.ensure(s).cases.find(c=>c.id===id)||null;
  }
  function getQuote(s,id){return ensure(s).quotes.find(q=>q.id===id)||null;}
  function known(s,actor,token,from){
    return s.npc[actor].knowledge.some(k=>(!from||k.source===from)&&String(k.topic).includes(token));
  }
  function opening(s,{caseId,priceYuan,payerOpeningYuan,providerOpeningYuan}){
    const e=ensure(s),c=caseOf(s,caseId);
    check(c&&c.type==="work"&&c.status==="discussed","需要双方先完成既有维修合作协商");
    check([c.from,c.to].sort().join(":")===PARTIES.slice().sort().join(":"),"仅限既有维修经营者与技术合作者的S级试验");
    check(known(s,c.from,c.id,c.to),"双方协商回执尚未送达发起方");
    const price=Number(priceYuan),payer=Number(payerOpeningYuan),provider=Number(providerOpeningYuan);
    check(validAmount(price)&&price>0&&validAmount(payer)&&validAmount(provider),"S级假设金额须为安全整数元");
    check(!e.fixtures[caseId],"此事务已设定假设经济条件，不能覆盖");
    check(!(PAYER in e.accounts)&&!(PROVIDER in e.accounts),"S级账户已有开局余额，不得再次注资");
    // Opening balances are unverified external endowments with an explicit S fixture origin,
    // not new money generated by the game or a real person.
    e.accounts[PAYER]=payer*100;e.accounts[PROVIDER]=provider*100;
    e.openingAccounts={P014:payer*100,P015:provider*100};
    const fixture={caseId,priceCents:price*100,createdAt:s.time,source:"S_EXPLICIT_OPERATOR_FIXTURE",
      approvedBy:"out_of_character_test_setup",payer:PAYER,provider:PROVIDER};
    e.fixtures[caseId]=fixture;
    log(s,{event:"fixture",caseId,text:"外视角明示S级测试条件；未报价、未付款，不推断真实资产。"});
    return fixture;
  }
  function available(s,actor,at=s.time){
    const e=ensure(s),out=[];
    if(!PARTIES.includes(actor))return out;
    if(E.plan(s,actor,at).kind!=="work")return out;
    for(const [caseId,fixture] of Object.entries(e.fixtures)){
      const c=caseOf(s,caseId);
      if(!c||c.status!=="discussed")continue;
      const quote=e.quotes.find(q=>q.caseId===caseId);
      if(!quote && actor===PROVIDER && known(s,PROVIDER,caseId,PAYER)){
        out.push({id:"issue_quote",label:"就已知维修协商提出S级测试报价"});
      } else if(quote && quote.status==="offered" && actor===PAYER && known(s,PAYER,quote.id,PROVIDER)){
        if(e.accounts[PAYER]>=quote.priceCents)out.push({id:"accept_quote",label:"条件具备，原则上接受S级报价"});
        out.push({id:"decline_quote",label:"拒绝或暂缓S级报价"});
      } else if(quote && quote.status==="accepted" && actor===PROVIDER &&
                known(s,PROVIDER,quote.id,PAYER) && !quote.claimedAt){
        out.push({id:"report_work",label:"汇报已完成的S级模拟事务，等待核验"});
      }
    }
    return out;
  }
  function log(s,detail){
    const e=ensure(s),line={at:s.time,npcId:detail.npcId||PAYER,
      kind:"economy",text:detail.text,event:detail.event,caseId:detail.caseId,
      grade:"S",visibility:"out_of_character"};
    e.history.push(line);if(e.history.length>500)e.history.shift();
    s.world.push(line);if(s.world.length>4000)s.world.shift();
    return line;
  }
  function apply(s,actor,action){
    check(available(s,actor).some(c=>c.id===action),"人物缺少报价/信息/日程/资金前置条件");
    const e=ensure(s),fixture=Object.values(e.fixtures).find(f=>{
      const quote=e.quotes.find(q=>q.caseId===f.caseId);
      if(action==="issue_quote")return !quote && actor===PROVIDER;
      if(!quote)return false;
      if(["accept_quote","decline_quote"].includes(action))return quote.status==="offered"&&actor===PAYER&&known(s,PAYER,quote.id,PROVIDER);
      return action==="report_work"&&quote.status==="accepted"&&actor===PROVIDER&&known(s,PROVIDER,quote.id,PAYER);
    });
    check(fixture,"没有可以处理的合法经济事务");
    let q=e.quotes.find(x=>x.caseId===fixture.caseId);
    if(action==="issue_quote"){
      q={id:"Q-"+String(++e.seq).padStart(5,"0"),caseId:fixture.caseId,
        payer:PAYER,provider:PROVIDER,priceCents:fixture.priceCents,
        proposedAt:s.time,status:"offered",acceptedAt:null,claimedAt:null,verifiedAt:null,paidAt:null,
        source:"S_EXPLICIT_OPERATOR_FIXTURE",completionEvidence:null};
      e.quotes.push(q);
      s.queue.push({type:"peerDeliver",at:s.time+15*MINUTE,from:PROVIDER,to:PAYER,
        text:q.id+"：维修合作报价为S级假设金额；不构成真实交易。",order:s.sequence+e.seq});
      log(s,{npcId:PROVIDER,event:"quote_offered",caseId:q.caseId,text:"技术合作者根据已知条件发送"+q.id+"的S级报价，尚无合同或付款。"});
    } else if(action==="accept_quote"){
      q.status="accepted";q.acceptedAt=s.time;
      s.queue.push({type:"peerDeliver",at:s.time+10*MINUTE,from:PAYER,to:PROVIDER,
        text:q.id+"：仅就S级测试金额原则上接受；未证明实际服务。",order:s.sequence+e.seq+1});
      log(s,{npcId:PAYER,event:"quote_accepted",caseId:q.caseId,text:"经营者原则同意"+q.id+"的S级条件，仍待完成工作与独立核验。"});
    } else if(action==="decline_quote"){
      q.status="declined";q.closedAt=s.time;
      s.queue.push({type:"peerDeliver",at:s.time+10*MINUTE,from:PAYER,to:PROVIDER,
        text:q.id+"：当前条件下拒绝报价。",order:s.sequence+e.seq+1});
      log(s,{npcId:PAYER,event:"quote_declined",caseId:q.caseId,text:"经营者拒绝"+q.id+"报价，没有生成任何支付义务。"});
    } else if(action==="report_work"){
      q.status="reported";q.claimedAt=s.time;
      s.queue.push({type:"peerDeliver",at:s.time+15*MINUTE,from:PROVIDER,to:PAYER,
        text:q.id+"：供应方报告模拟事项完成，尚未经独立核验。",order:s.sequence+e.seq+1});
      log(s,{npcId:PROVIDER,event:"work_reported",caseId:q.caseId,text:"技术合作者报告"+q.id+"已模拟完成；不能凭报告本身结算。"});
    }
    return q;
  }
  function verifyDelivery(s,{quoteId,confirmation}){
    const e=ensure(s),q=getQuote(s,quoteId);
    check(q&&q.status==="reported"&&q.claimedAt!==null,"尚未达到可核验的工作报告阶段");
    check(confirmation==="S_SIMULATED_DELIVERY_VERIFIED","须由外视角明确确认S级测试履约证据");
    check(known(s,PAYER,q.id,PROVIDER),"委托方尚未收到工作报告");
    q.status="verified";q.verifiedAt=s.time;q.completionEvidence="S_SIMULATED_DELIVERY_VERIFIED";
    log(s,{npcId:PAYER,event:"verified",caseId:q.caseId,text:"外视角确认"+q.id+"仅在S级沙盒中模拟交付，仍未付款。"});
    return q;
  }
  function settle(s,{quoteId,confirmation}){
    const e=ensure(s),q=getQuote(s,quoteId);
    check(q&&q.status==="verified"&&q.verifiedAt!==null,"必须先确认模拟履约");
    check(confirmation==="S_AUTHORIZE_DOUBLE_ENTRY","需要外视角明确授权进行S级成对账本模拟");
    check(!e.transfers.some(t=>t.quoteId===quoteId),"不可重复付款");
    check(audit(s).length===0,"经济账本审计失败，拒绝继续结算");
    const balance=e.accounts[PAYER],received=e.accounts[PROVIDER],sum=q.priceCents;
    check(validAmount(balance)&&validAmount(received),"双方资金未知，禁止付款");
    check(Number.isSafeInteger(sum)&&sum>0&&balance>=sum,"账户余额不足，不能记账");
    check(Number.isSafeInteger(received+sum),"接受方余额超出安全整数");
    // Atomic pair: validate all conditions before changing any balance.
    const txId="TX-"+String(e.transfers.length+1).padStart(5,"0");
    const debit={txId,at:s.time,account:PAYER,deltaCents:-sum,quoteId,grade:"S"};
    const credit={txId,at:s.time,account:PROVIDER,deltaCents:sum,quoteId,grade:"S"};
    e.accounts[PAYER]=balance-sum;e.accounts[PROVIDER]=received+sum;
    e.ledger.push(debit,credit);
    e.transfers.push({id:txId,quoteId,at:s.time,payer:PAYER,recipient:PROVIDER,
      amountCents:sum,status:"S_SIMULATED_SETTLEMENT"});
    q.status="settled";q.paidAt=s.time;
    log(s,{npcId:PAYER,event:"settled",caseId:q.caseId,text:"S级试验成对记账"+txId+"，双方余额一减一增；不代表真实银行支付。"});
    return {txId,debit,credit};
  }
  function audit(s){
    const e=ensure(s),errors=[];
    for(const q of e.quotes){
      if(!e.fixtures[q.caseId])errors.push("quote missing fixture "+q.id);
      if(q.status==="settled"&&!e.transfers.some(t=>t.quoteId===q.id))errors.push("unbacked settlement "+q.id);
    }
    const ids=e.transfers.map(t=>t.quoteId);
    if(ids.length!==new Set(ids).size)errors.push("duplicate settlement");
    for(const t of e.transfers){
      const entries=e.ledger.filter(l=>l.txId===t.id);
      if(entries.length!==2||entries.reduce((a,b)=>a+b.deltaCents,0)!==0)errors.push("unbalanced transfer "+t.id);
      if(entries.some(l=>!["P014","P015"].includes(l.account)))errors.push("unknown payee "+t.id);
    }
    if(Object.values(e.accounts).some(x=>!validAmount(x)))errors.push("invalid balance");
    if(e.transfers.length>0&&!e.openingAccounts)errors.push("opening balances not recorded");
    for(const id of PARTIES){
      if(e.accounts[id]===undefined)continue;
      const opening=e.openingAccounts?.[id];
      if(!validAmount(opening)){errors.push("unknown opening balance "+id);continue;}
      const computed=opening+e.ledger.filter(l=>l.account===id).reduce((acc,l)=>acc+l.deltaCents,0);
      if(computed!==e.accounts[id])errors.push("balance does not reconcile "+id);
    }
    for(const l of e.ledger){
      if(!e.transfers.some(t=>t.id===l.txId&&t.quoteId===l.quoteId))errors.push("orphan ledger entry "+l.txId);
      if(!Number.isSafeInteger(l.deltaCents))errors.push("invalid ledger amount");
    }
    return errors;
  }
  return Object.freeze({ensure,opening,available,apply,verifyDelivery,settle,audit,getQuote});
});
